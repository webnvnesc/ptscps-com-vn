#!/usr/bin/env python3
"""Ensure real anonymous homepage separates desktop and mobile cache variants."""
import urllib.request,json,re,hashlib,time,sys
root="https://ptscps.com.vn/"
agents={
 "desktop":"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Safari/537.36",
 "mobile":"Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Mobile Safari/537.36",
}
passed=True
for cycle in range(1,4):
 for device,ua in agents.items():
  req=urllib.request.Request(root,headers={"User-Agent":ua,"Accept":"text/html","Accept-Encoding":"identity"})
  try:
   with urllib.request.urlopen(req,timeout=35) as r:
    html=r.read(2500000).decode("utf-8","replace");status=r.status
   matched=re.search(r'<body\b[^>]*class=["\x27]([^"\x27]+)',html,re.I)
   cls=matched.group(1).split() if matched else []
   mode=[x for x in cls if x in ("is-desktop","is-mobile")]
   guard="ptscps-header-logo-safety-css" in html
   cache="Cached page generated by WP-Super-Cache" in html
   good=status==200 and mode==["is-"+device] and guard and cache
   passed &= good
   print("WPSC_DEVICE_QA "+json.dumps({"cycle":cycle,"device":device,"status":status,"mode":mode,"guard":guard,"cached":cache,"htmlHash":hashlib.sha256(html.encode()).hexdigest()[:12],"passed":good}),flush=True)
  except Exception as e:
   passed=False;print("WPSC_DEVICE_QA_ERROR "+json.dumps({"cycle":cycle,"device":device,"error":str(e)[:220]}),flush=True)
 time.sleep(1)
print("WPSC_DEVICE_SUMMARY "+json.dumps({"cases":6,"passed":passed}),flush=True)
if not passed:sys.exit(1)
