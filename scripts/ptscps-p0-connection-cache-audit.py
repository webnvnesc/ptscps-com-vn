#!/usr/bin/env python3
"""P0 anonymous first-visit TTFB audit. Public GET only, no hosting mutations.
Measure fresh TLS connections separately from multiple URLs on a reused H2 connection.
Time_pretransfer includes handshake on fresh connects; the delta to first byte
is a network+origin wait proxy, NOT a certified PHP or cache HIT/MISS time.
"""
import json
import os
import re
import statistics
import subprocess
from collections import defaultdict

PAGES = {
    "home": "https://ptscps.com.vn/",
    "news": "https://ptscps.com.vn/c/hoat-dong-cua-cong-ty",
    "service": "https://ptscps.com.vn/dich-vu/van-hanh-va-bao-duong-fpso-fso-mopu",
}
AGENTS = {
    "mobile": "Mozilla/5.0 (Linux; Android 13; Pixel 6) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Mobile Safari/537.36",
    "desktop": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Safari/537.36",
}
FIELDS = ["http_code", "http_version", "num_connects", "time_namelookup",
          "time_connect", "time_appconnect", "time_pretransfer",
          "time_starttransfer", "time_total", "size_download"]
ROWS = []
def curl_piece(name, user_agent, mode, cycle):
    return [
        "-sS", "-L", "--http2", "--compressed", "--max-time", "45",
        "--connect-timeout", "15", "--output", "/dev/null",
        "--header", "Accept: text/html", "--user-agent", user_agent,
        "--write-out", "PTSCPS|"+name+"|"+mode+"|"+str(cycle)+"|"+
        "|".join("%{"+f+"}" for f in FIELDS)+"\\n",
        PAGES[name],
    ]

def parse_run(output, agent):
    for line in output.splitlines():
        if not line.startswith("PTSCPS|"):
            continue
        parts = line.split("|")
        if len(parts) != 4 + len(FIELDS):
            raise ValueError("unexpected curl field count")
        page, mode, cycle = parts[1:4]
        values = dict(zip(FIELDS, parts[4:]))
        row = {"agent": agent, "page": page, "mode": mode, "cycle": int(cycle)}
        row["code"] = int(values["http_code"])
        row["httpVersion"] = values["http_version"]
        row["newConnections"] = int(values["num_connects"])
        for field in FIELDS[3:-1]:
            row[field.replace("time_", "")+"Ms"] = round(float(values[field])*1000)
        row["originWaitProxyMs"] = round(
            (float(values["time_starttransfer"])-float(values["time_pretransfer"]))*1000)
        row["bytes"] = int(float(values["size_download"]))
        ROWS.append(row)
        print("P0_ROW "+json.dumps(row), flush=True)
        if row["code"] != 200:
            raise ValueError("non-200 HTML: "+str(row))

def run(args, agent):
    p = subprocess.run(["curl", *args], text=True, capture_output=True, timeout=360)
    if p.returncode != 0:
        raise RuntimeError("curl failed: "+p.stderr[-300:])
    parse_run(p.stdout, agent)

def cache_hint(page, agent):
    p = subprocess.run([
        "curl", "-sS", "-L", "--http2", "--compressed", "--max-time", "45",
        "-H", "Accept: text/html", "-A", agent, PAGES[page],
    ], text=True, capture_output=True, timeout=55)
    if p.returncode:
        return {"error": p.stderr[-100:]}
    tail = p.stdout[-2600:].lower()
    # Public markup marker, not server cache HIT proof.
    patterns = ["cached page generated by wp-super-cache", "wp-super-cache",
                "dynamic page generated", "super cache"]
    return {
        "wpSuperCacheHtmlMarker": any(x in tail for x in patterns),
        "markerType": next((x for x in patterns if x in tail), None),
    }

def median(vals):
    return round(statistics.median(vals)) if vals else None

def main():
    for agent, ua in AGENTS.items():
        for cycle in range(1, 4):
            for page in PAGES:
                run(curl_piece(page, ua, "fresh-connection", cycle), agent)
        # One curl process: curl can reuse DNS/TLS/H2 connections across transfers.
        sequence = []
        for cycle in range(1, 8):
            names = list(PAGES)
            if cycle % 2 == 0:
                names.reverse()
            for page in names:
                sequence.append(curl_piece(page, ua, "same-process", cycle))
        args = []
        for index, piece in enumerate(sequence):
            if index:
                args.append("--next")
            args.extend(piece)
        run(args, agent)
    grouped = defaultdict(list)
    for row in ROWS:
        grouped[(row["agent"],row["page"],row["mode"])].append(row)
    summaries = []
    for (agent,page,mode), rows in sorted(grouped.items()):
        summary = {
            "agent":agent, "page":page, "mode":mode, "n":len(rows),
            "medianTtfbMs":median([x["starttransferMs"] for x in rows]),
            "medianOriginWaitProxyMs":median([x["originWaitProxyMs"] for x in rows]),
            "medianTlsMs":median([x["appconnectMs"] for x in rows]),
            "newConnections":sum(x["newConnections"] for x in rows)
        }
        summaries.append(summary)
        print("P0_SUMMARY "+json.dumps(summary), flush=True)
    markers = {name:cache_hint(name,AGENTS["mobile"]) for name in PAGES}
    print("P0_MARKERS "+json.dumps(markers),flush=True)
    out={"rows":ROWS,"summary":summaries,"markers":markers,
         "caveat":"No explicit HIT/MISS status instrumented. Origin wait includes network and any queuing."}
    os.makedirs("ptscps-p0-evidence",exist_ok=True)
    with open("ptscps-p0-evidence/results.json","w",encoding="utf-8") as f:
        json.dump(out,f,indent=2)
if __name__ == "__main__":
    main()
