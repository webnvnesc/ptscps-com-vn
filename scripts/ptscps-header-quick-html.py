#!/usr/bin/env python3
"""Quick read-only homepage HTML header fingerprint on multiple clean visits."""
import urllib.request, re, hashlib, json, time, collections, html
url="https://ptscps.com.vn/"
out=[]
for i in range(12):
  ua="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/154 Safari/537.36" if i%2==0 else "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 Chrome/154 Safari/537.36"
  req=urllib.request.Request(url,headers={"User-Agent":ua,"Accept":"text/html","Cache-Control":"no-cache" if i>5 else "max-age=0"})
  with urllib.request.urlopen(req,timeout=24) as resp:
    txt=resp.read(1800000).decode("utf-8","replace")
    headers=resp.headers
    status=resp.status
  logos=re.findall(r'<img\b[^>]*tie-logo-img[^>]*>',txt,re.I)
  logo=next((x for x in logos if "tie-logo-img-default" in x),"")
  search=re.search(r'<form\b[^>]*(?:search|s-form)[^>]*>',txt,re.I)
  allcss=re.findall(r'<link\b[^>]*rel=["\']stylesheet["\'][^>]*>',txt,re.I)
  row={"i":i,"status":status,"bodyHash":hashlib.sha256(txt.encode()).hexdigest()[:12],
    "bytes":len(txt),"logoCount":len(logos),"logoHash":hashlib.sha256(logo.encode()).hexdigest()[:12],
    "logoHtml":logo[:350],"searchForm":bool(search),
    "stylesheets":len(allcss),"bodyCacheTag":bool("Cached page generated by WP-Super-Cache" in txt),
    "cacheControl":headers.get("Cache-Control"),"vary":headers.get("Vary")}
  out.append(row);print("HTML_COMPARE "+json.dumps(row),flush=True)
print("HTML_SUMMARY "+json.dumps({"n":len(out),"distinctBodyHashes":len(set(x["bodyHash"] for x in out)),
 "distinctLogoHashes":len(set(x["logoHash"] for x in out)),
 "searchFormAll":all(x["searchForm"] for x in out),"logoAll":all(x["logoCount"]>0 for x in out),
 "cacheTagCount":sum(x["bodyCacheTag"] for x in out)}),flush=True)
