#!/usr/bin/env python3
"""Compare cached homepage to cache-bypassed homepage with real mobile and desktop UAs; read-only."""
import urllib.request,urllib.error,re,json,hashlib,time
root="https://ptscps.com.vn/"
agents={
"desktop":"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Safari/537.36",
"mobile":"Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Mobile Safari/537.36"
}
for i in range(2):
 for target in ("plain","bypass"):
  for name,ua in agents.items():
   url=root if target=="plain" else root+"?ptscps_cssom_cache_proof="+str(i+1)+"_"+name
   try:
    req=urllib.request.Request(url,headers={"User-Agent":ua,"Accept":"text/html","Accept-Encoding":"identity"})
    with urllib.request.urlopen(req,timeout=30) as r:
     page=r.read(2000000).decode("utf-8","replace");status=r.status;hdr=dict(r.headers.items())
    body=re.search(r'<body\b[^>]*class=["\x27]([^"\x27]+)',page,re.I)
    names=body.group(1).split() if body else []
    logo=re.search(r'<img\b[^>]*tie-logo-img-default[^>]*>',page,re.I)
    print("CACHE_VARIANT "+json.dumps({"iter":i+1,"target":target,"agent":name,"status":status,
      "bodyMode":[x for x in names if x in ("is-mobile","is-desktop")],
      "mobileHeader":"mobile-header-default" in page,
      "logoHTML":(logo.group(0) if logo else "")[:340],
      "guard":"ptscps-header-logo-safety-css" in page,
      "bodyHash":hashlib.sha256(page.encode()).hexdigest()[:12],
      "cacheTag":re.findall(r'(?:Cached|Dynamic) page generated by WP-Super-Cache[^\r\n<]*',page,re.I)[-1:] or [],
      "cacheHeader":{k:v for k,v in hdr.items() if k.lower() in ("age","x-cache","cache-control","vary")},
      "contentLength":len(page)},ensure_ascii=False),flush=True)
   except Exception as e:
    print("CACHE_VARIANT_ERROR "+json.dumps({"iter":i+1,"target":target,"agent":name,"error":str(e)[:400]}),flush=True)
